export function canonicalBlogSlug(slug) {
  return slugAliases[slug] || slug;
}

export function getBlogDate(article) {
  if (!article?.meta) return "";
  return article.meta.includes("•")
    ? article.meta.split("•").pop().trim()
    : article.meta;
}

export function getRelatedBlogs(slug, count = 2) {
  const current = canonicalBlogSlug(slug);
  const index = blogArticles.findIndex((article) => article.slug === current);
  if (blogArticles.length <= 1) return [];
  if (index === -1) return blogArticles.slice(0, count);

  const related = [];
  for (
    let step = 1;
    related.length < count && step < blogArticles.length;
    step += 1
  ) {
    related.push(blogArticles[(index + step) % blogArticles.length]);
  }
  return related;
}
